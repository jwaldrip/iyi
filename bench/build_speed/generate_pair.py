#!/usr/bin/env python3
"""Writes the same program twice: once in iyi, once in Go.

`hello` is the only pair in this bench that needs no argument about being a
pair — one line, one `puts`. It is also the pair that says nothing about what
happens when there is user code, and `webapp.iyi` costing the same as `hello`
is the measurement that made that worth fixing (SPEC.md 0.1.0 item 5).

Writing a second pair by hand invites the question this bench exists to avoid:
whether the two programs are really the same program. So neither is written by
hand. Both come out of the loop below, from the same numbers, and the check
that they agree is that the two binaries print the same thing — which
`build_speed.py` runs before it times anything.

What the program does is deliberately dull: `types` structs, each with two
fields, an arithmetic method, a method that takes another of its kind, and a
name. Then a main that constructs one of each, adds up what they answer, and
prints the total and one string length. Nothing here is idiomatic in either
language, and it is not meant to be: it is the same shape twice, so that what
differs between the columns is the compiler.

Everything stays inside `% 1000`, because Crystal's `Int32` raises on overflow
and Go's wraps — a program that overflowed would not be one program any more.
"""

import sys

HEADER_IYI = """\
# Generated by bench/build_speed/generate_pair.py — do not edit.
#
# The iyi half of the bench's second pair. See the generator for what this is
# and why it is not written by hand.
module bench/medium
"""

HEADER_GO = """\
// Generated by bench/build_speed/generate_pair.py — do not edit.
//
// The Go half of the bench's second pair. See the generator for what this is
// and why it is not written by hand.
package main

import "fmt"
"""


def widget_iyi(index):
    return f"""
pub struct Widget{index}
  @a : Int32
  @b : Int32

  def initialize(@a : Int32, @b : Int32)
  end

  def score : Int32
    ((@a * {3 + index % 7}) + (@b * {5 + index % 11})) % 1000
  end

  def blend(other : Widget{index}) : Int32
    (score + other.score) % 1000
  end

  def label : String
    "widget-{index}"
  end
end
"""


def widget_go(index):
    return f"""
type Widget{index} struct {{
	a int32
	b int32
}}

func (w Widget{index}) Score() int32 {{
	return ((w.a * {3 + index % 7}) + (w.b * {5 + index % 11})) % 1000
}}

func (w Widget{index}) Blend(other Widget{index}) int32 {{
	return (w.Score() + other.Score()) % 1000
}}

func (w Widget{index}) Label() string {{
	return "widget-{index}"
}}
"""


def main_iyi(types):
    lines = ["", "total = 0", "names = 0", ""]
    for index in range(types):
        a, b = index % 97, index % 89
        lines.append(f"w{index} = Widget{index}.new({a}, {b})")
        lines.append(f"total = (total + w{index}.score + w{index}.blend(w{index})) % 100000")
        lines.append(f"names = names + w{index}.label.size")
    lines += ["", "puts total", "puts names", ""]
    return "\n".join(lines)


def main_go(types):
    lines = ["", "func main() {", "\tvar total int32 = 0", "\tvar names int = 0", ""]
    for index in range(types):
        a, b = index % 97, index % 89
        lines.append(f"\tw{index} := Widget{index}{{a: {a}, b: {b}}}")
        lines.append(f"\ttotal = (total + w{index}.Score() + w{index}.Blend(w{index})) % 100000")
        lines.append(f"\tnames = names + len(w{index}.Label())")
    lines += ["", "\tfmt.Println(total)", "\tfmt.Println(names)", "}", ""]
    return "\n".join(lines)


def write_pair(directory, types):
    """Writes `medium.iyi` and `medium.go` into *directory*, returning both paths."""
    iyi = directory / "medium.iyi"
    go = directory / "medium.go"
    iyi.write_text(HEADER_IYI + "".join(widget_iyi(i) for i in range(types)) + main_iyi(types))
    go.write_text(HEADER_GO + "".join(widget_go(i) for i in range(types)) + main_go(types))
    return iyi, go


if __name__ == "__main__":
    import pathlib

    types = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    where = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else ".")
    iyi, go = write_pair(where, types)
    for path in (iyi, go):
        print(f"{path}: {len(path.read_text().splitlines())} lines")
